CREATE OR REPLACE FUNCTION public.approve_accommodation_request(
    p_accommodation_id integer,
    p_room_id integer,
    p_updated_by text
)
RETURNS SETOF public.accommodation
LANGUAGE plpgsql
AS $$
DECLARE
    v_request public.accommodation%ROWTYPE;
    v_room public.room%ROWTYPE;
    v_occupied integer;
BEGIN
    SELECT *
    INTO v_request
    FROM public.accommodation
    WHERE accommodation_id = p_accommodation_id
      AND is_delete IS NOT TRUE
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Accommodation request not found' USING ERRCODE = 'P1001';
    END IF;

    IF v_request.request_status <> 'Pending' THEN
        RAISE EXCEPTION 'Only pending requests can be approved' USING ERRCODE = 'P1002';
    END IF;

    IF v_request.check_in_date IS NULL
       OR v_request.check_out_date IS NULL
       OR v_request.check_out_date <= v_request.check_in_date THEN
        RAISE EXCEPTION 'The request has invalid stay dates' USING ERRCODE = 'P1005';
    END IF;

    SELECT *
    INTO v_room
    FROM public.room
    WHERE room_id = p_room_id
      AND is_active = true
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'The selected room is not active' USING ERRCODE = 'P1003';
    END IF;

    SELECT COUNT(*)
    INTO v_occupied
    FROM public.accommodation AS a
    WHERE a.room_id = p_room_id
      AND a.request_status = 'Approved'
      AND a.is_delete IS NOT TRUE
      AND a.accommodation_id <> p_accommodation_id
      AND a.check_in_date < v_request.check_out_date
      AND a.check_out_date > v_request.check_in_date;

    IF v_occupied >= v_room.capacity THEN
        RAISE EXCEPTION 'The selected room has no beds available for these dates'
            USING ERRCODE = 'P1004';
    END IF;

    UPDATE public.accommodation
    SET request_status = 'Approved',
        room_id = v_room.room_id,
        building_name = v_room.building_name,
        room_number = v_room.room_number,
        updated_by = p_updated_by,
        updated_date = CURRENT_DATE,
        updated_time = LOCALTIME(0)
    WHERE accommodation_id = p_accommodation_id
    RETURNING * INTO v_request;

    RETURN NEXT v_request;
END
$$;

REVOKE ALL ON FUNCTION public.approve_accommodation_request(integer, integer, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.approve_accommodation_request(integer, integer, text) TO service_role;
