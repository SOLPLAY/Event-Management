CREATE TABLE IF NOT EXISTS public.room (
    room_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_name text NOT NULL,
    room_number text NOT NULL,
    capacity integer NOT NULL CHECK (capacity > 0),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT room_building_room_number_key UNIQUE (building_name, room_number)
);

ALTER TABLE public.accommodation
    ADD COLUMN IF NOT EXISTS room_id integer
        REFERENCES public.room (room_id),
    ADD COLUMN IF NOT EXISTS request_status text,
    ADD COLUMN IF NOT EXISTS created_by text,
    ADD COLUMN IF NOT EXISTS created_date date,
    ADD COLUMN IF NOT EXISTS updated_by text,
    ADD COLUMN IF NOT EXISTS updated_date date,
    ADD COLUMN IF NOT EXISTS updated_time time without time zone;

ALTER TABLE public.accommodation
    ALTER COLUMN building_name DROP NOT NULL,
    ALTER COLUMN room_number DROP NOT NULL;

UPDATE public.accommodation
SET request_status = CASE
    WHEN room_id IS NOT NULL
        OR (NULLIF(building_name, '') IS NOT NULL AND NULLIF(room_number, '') IS NOT NULL)
    THEN 'Approved'
    ELSE 'Pending'
END
WHERE request_status IS NULL;

ALTER TABLE public.accommodation
    ALTER COLUMN request_status SET DEFAULT 'Pending',
    ALTER COLUMN request_status SET NOT NULL;

-- Run this again after adding room rows to connect legacy assigned stays to room capacity.
UPDATE public.accommodation AS a
SET room_id = r.room_id
FROM public.room AS r
WHERE a.room_id IS NULL
  AND a.request_status = 'Approved'
  AND a.building_name = r.building_name
  AND a.room_number = r.room_number;

