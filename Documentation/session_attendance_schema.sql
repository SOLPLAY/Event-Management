CREATE TABLE IF NOT EXISTS public.session_attendance (
    attendance_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id integer NOT NULL
        REFERENCES public.session (session_id) ON DELETE CASCADE,
    registration_id integer NOT NULL
        REFERENCES public.registration (registration_id) ON DELETE CASCADE,
    attendance_status text
        CHECK (attendance_status IN ('Present', 'Absent')),
    marked_by text,
    marked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_attendance_session_registration_key
        UNIQUE (session_id, registration_id)
);

CREATE INDEX IF NOT EXISTS session_attendance_registration_id_idx
    ON public.session_attendance (registration_id);
