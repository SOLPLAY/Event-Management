ALTER TABLE public.advertisement
    ADD COLUMN IF NOT EXISTS media_path text,
    ADD COLUMN IF NOT EXISTS media_content_type text,
    ADD COLUMN IF NOT EXISTS media_file_name text;

CREATE TABLE IF NOT EXISTS public.event_sponsor (
    sponsor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL
        REFERENCES public.event (event_id) ON DELETE CASCADE,
    sponsor_name text NOT NULL,
    sponsorship_level text NOT NULL DEFAULT 'Sponsor',
    contact_person text,
    contact_email text,
    contact_phone text,
    sponsorship_amount numeric(12, 2)
        CHECK (sponsorship_amount IS NULL OR sponsorship_amount >= 0),
    notes text,
    is_delete boolean NOT NULL DEFAULT false,
    created_by text NOT NULL,
    created_date date NOT NULL DEFAULT CURRENT_DATE,
    created_time time without time zone NOT NULL DEFAULT LOCALTIME(0),
    updated_by text,
    updated_date date,
    updated_time time without time zone
);

CREATE INDEX IF NOT EXISTS event_sponsor_event_id_idx
    ON public.event_sponsor (event_id);

ALTER TABLE public.event_sponsor ENABLE ROW LEVEL SECURITY;

